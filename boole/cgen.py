"""Boole → C codegen with int unboxing, classes, exceptions, modules."""

from __future__ import annotations

from pathlib import Path

from boole import ast as A
from boole.errors import BooleError
from boole.parser import parse


class CGen:
    def __init__(self, path: str = "<stdin>"):
        self.path = path
        self.lines: list[str] = []
        self.indent = 0
        self.tmp = 0
        self.locals: set[str] = set()
        self.boxed_locals: set[str] = set()
        self.int_locals: set[str] = set()
        self.fn_names: set[str] = set()
        self.class_names: set[str] = set()
        self.module_names: set[str] = set()
        self.classes: dict[str, A.ClassDef] = {}
        self.decls: list[str] = []
        self.body_start = 0
        self.imported_funcs: list[A.FuncDef] = []
        self.imported_classes: list[A.ClassDef] = []
        self.import_inits: list[tuple[str, str]] = []  # (modname, kind) kind=math|json|local

    def emit(self, line: str = ""):
        self.lines.append(("  " * self.indent) + line)

    def fresh(self, prefix="t"):
        self.tmp += 1
        return f"{prefix}{self.tmp}"

    def unsupported(self, node, msg):
        raise BooleError("CompileError", msg, getattr(node, "line", 1), getattr(node, "col", 1))

    def c_ident(self, name: str) -> str:
        return "bl_" + name.replace(".", "_")

    def method_ident(self, cls: str, method: str) -> str:
        return f"bl_{cls}_{method}"

    def generate(self, program: A.Program) -> str:
        body = list(program.body)
        body = self._expand_imports(body)

        for stmt in body:
            if isinstance(stmt, A.FuncDef):
                self.fn_names.add(stmt.name)
            if isinstance(stmt, A.ClassDef):
                self.class_names.add(stmt.name)
                self.classes[stmt.name] = stmt

        out = [
            "/* Generated by Boole — native C backend */",
            '#include "boole_rt.h"',
            '#include "boole_oop.h"',
            "#include <stdio.h>",
            "#include <stdint.h>",
            "#include <setjmp.h>",
            "#include <string.h>",
            "",
        ]

        # Forward decls for free functions
        for stmt in body:
            if isinstance(stmt, A.FuncDef):
                params = ", ".join(["BooleValue"] * len(stmt.params))
                if stmt.params:
                    out.append(f"static BooleValue {self.c_ident(stmt.name)}({params});")
                else:
                    out.append(f"static BooleValue {self.c_ident(stmt.name)}(void);")

        # Methods + class structs
        for cls_name, cls in self.classes.items():
            for item in cls.body:
                if isinstance(item, A.FuncDef):
                    out.append(
                        f"static BooleValue {self.method_ident(cls_name, item.name)}(int argc, BooleValue *argv);"
                    )
        out.append("")

        for cls_name, cls in self.classes.items():
            methods = [item for item in cls.body if isinstance(item, A.FuncDef)]
            out.append(f"static const BooleMethodEntry bl_methods_{cls_name}[] = {{")
            for item in methods:
                out.append(
                    f'  {{"{item.name}", {self.method_ident(cls_name, item.name)}}},'
                )
            out.append("};")
            base = f"&bl_class_{cls.base}" if cls.base else "NULL"
            if cls.base and cls.base not in self.classes:
                self.unsupported(cls, f"unknown base class '{cls.base}'")
            out.append(f"static const BooleClass bl_class_{cls_name} = {{")
            out.append(f'  "{cls_name}", {base}, bl_methods_{cls_name}, {len(methods)}')
            out.append("};")
            out.append("")

        # Method bodies
        for cls_name, cls in self.classes.items():
            for item in cls.body:
                if isinstance(item, A.FuncDef):
                    out.append(self.gen_method(cls_name, item))
                    out.append("")

        # Free functions
        for stmt in body:
            if isinstance(stmt, A.FuncDef):
                out.append(self.gen_func(stmt))
                out.append("")

        # Wrappers so modules can hold free functions
        for stmt in body:
            if isinstance(stmt, A.FuncDef) and stmt.name.startswith("mod_"):
                continue

        self.lines = []
        self.indent = 0
        self.locals = set()
        self.boxed_locals = set()
        self.int_locals = set()
        self.decls = []
        self.emit("int main(void) {")
        self.indent += 1
        self.body_start = len(self.lines)

        # Bind classes as values
        for cls_name in self.classes:
            self.ensure_val(cls_name)
            self.emit(
                f"bv_release({self.c_ident(cls_name)}); "
                f"{self.c_ident(cls_name)} = bv_class(&bl_class_{cls_name});"
            )

        # Bind imports
        for modname, kind in self.import_inits:
            self.ensure_val(modname)
            if kind == "math":
                self.emit(
                    f"bv_release({self.c_ident(modname)}); "
                    f"{self.c_ident(modname)} = bv_mod_math();"
                )
            elif kind == "json":
                self.emit(
                    f"bv_release({self.c_ident(modname)}); "
                    f"{self.c_ident(modname)} = bv_mod_json();"
                )
            else:
                # local module: attrs filled with functions named mod__fn
                self.emit(
                    f"bv_release({self.c_ident(modname)}); "
                    f"{self.c_ident(modname)} = bv_module(\"{modname}\");"
                )
                for fn in self.imported_funcs:
                    if fn.name.startswith(f"{modname}__"):
                        short = fn.name[len(modname) + 2 :]
                        wrap = self.c_ident(fn.name) + "_entry"
                        self.emit(
                            f"bv_setattr({self.c_ident(modname)}, \"{short}\", "
                            f"bv_func({wrap}, \"{short}\"));"
                        )

        for stmt in body:
            if isinstance(stmt, (A.FuncDef, A.ClassDef, A.ImportStmt)):
                continue
            self.gen_stmt(stmt)
        self.emit("return 0;")
        self._flush_decls()
        self.indent -= 1
        self.emit("}")
        out.extend(self.lines)
        out.append("")

        wraps = [self.gen_func_entry_wrapper(fn) for fn in self.imported_funcs]
        return "\n".join(self._inject_wrappers(out, wraps))

    def _inject_wrappers(self, out: list[str], wraps: list[str]) -> list[str]:
        if not wraps:
            return out
        # Place wrappers before main
        text = "\n".join(out)
        parts = text.rsplit("int main(void)", 1)
        if len(parts) != 2:
            return out + wraps
        return (parts[0] + "\n".join(wraps) + "\nint main(void)" + parts[1]).split("\n")

    def _expand_imports(self, body: list) -> list:
        result = []
        base = Path(self.path).resolve().parent if self.path not in ("<stdin>", "") else Path.cwd()
        for stmt in body:
            if not isinstance(stmt, A.ImportStmt):
                result.append(stmt)
                continue
            name = stmt.name
            if name == "math":
                self.import_inits.append((name, "math"))
                self.module_names.add(name)
                continue
            if name == "json":
                self.import_inits.append((name, "json"))
                self.module_names.add(name)
                continue
            if name == "sys":
                self.unsupported(stmt, "import sys is interpreter-only in native v0.1")
            # local module
            file_path = base.joinpath(*name.split(".")).with_suffix(".boole")
            if not file_path.is_file():
                self.unsupported(stmt, f"cannot import '{name}' (missing {file_path})")
            mod_prog = parse(file_path.read_text(encoding="utf-8"), str(file_path))
            self.import_inits.append((name, "local"))
            self.module_names.add(name)
            for item in mod_prog.body:
                if isinstance(item, A.FuncDef):
                    renamed = A.FuncDef(
                        name=f"{name}__{item.name}",
                        params=item.params,
                        returns=item.returns,
                        body=item.body,
                        is_static=item.is_static,
                        line=item.line,
                        col=item.col,
                    )
                    self.imported_funcs.append(renamed)
                    result.append(renamed)
                    self.fn_names.add(renamed.name)
                elif isinstance(item, A.ClassDef):
                    renamed = A.ClassDef(
                        name=f"{name}__{item.name}",
                        base=item.base,
                        body=item.body,
                        line=item.line,
                        col=item.col,
                    )
                    self.imported_classes.append(renamed)
                    result.append(renamed)
                elif isinstance(item, A.ImportStmt):
                    self.unsupported(item, "nested imports not supported in native v0.1")
                else:
                    # skip module-level statements for now
                    pass
        return result

    def gen_func_entry_wrapper(self, node: A.FuncDef) -> str:
        n = len(node.params)
        lines = [
            f"static BooleValue {self.c_ident(node.name)}_entry(int argc, BooleValue *argv) {{",
            f"  if (argc != {n}) bv_die(\"bad argument count\");",
        ]
        args = ", ".join(f"argv[{i}]" for i in range(n)) if n else ""
        lines.append(f"  return {self.c_ident(node.name)}({args});")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def gen_method(self, cls_name: str, node: A.FuncDef) -> str:
        saved = (
            self.lines,
            self.indent,
            self.locals,
            self.boxed_locals,
            self.int_locals,
            self.decls,
            self.body_start,
        )
        self.lines = []
        self.indent = 0
        self.locals = {p.name for p in node.params}
        self.boxed_locals = {p.name for p in node.params}
        self.int_locals = set()
        self.decls = []
        for p in node.params:
            if p.typ and isinstance(p.typ, A.NamedType) and p.typ.name in ("int", "Int"):
                self.int_locals.add(p.name)
        self.emit(
            f"static BooleValue {self.method_ident(cls_name, node.name)}(int argc, BooleValue *argv) {{"
        )
        self.indent += 1
        self.body_start = len(self.lines)
        self.emit(f"if (argc < {len(node.params)}) bv_die(\"missing method arguments\");")
        for i, p in enumerate(node.params):
            self.emit(f"BooleValue {self.c_ident(p.name)} = bv_retain(argv[{i}]);")
            if p.name in self.int_locals:
                self.emit(f"int64_t {self.c_ident(p.name)}_i = bv_as_int({self.c_ident(p.name)});")
        for stmt in node.body:
            self.gen_stmt(stmt)
        # release params
        for p in node.params:
            self.emit(f"bv_release({self.c_ident(p.name)});")
        self.emit("return bv_none();")
        self._flush_decls()
        self.indent -= 1
        self.emit("}")
        text = "\n".join(self.lines)
        (
            self.lines,
            self.indent,
            self.locals,
            self.boxed_locals,
            self.int_locals,
            self.decls,
            self.body_start,
        ) = saved
        return text

    def _flush_decls(self):
        """Insert function-scoped locals before the body (not inside loops)."""
        if not self.decls:
            return
        for decl in reversed(self.decls):
            self.lines.insert(self.body_start, ("  " * 1) + decl)
        self.decls = []

    def gen_func(self, node: A.FuncDef) -> str:
        saved = (
            self.lines,
            self.indent,
            self.locals,
            self.boxed_locals,
            self.int_locals,
            self.decls,
            self.body_start,
        )
        self.lines = []
        self.indent = 0
        self.locals = {p.name for p in node.params}
        # Params arrive as BooleValue; mark them boxed so later demotion is safe.
        self.boxed_locals = {p.name for p in node.params}
        self.int_locals = set()
        self.decls = []
        for p in node.params:
            if p.typ and isinstance(p.typ, A.NamedType) and p.typ.name in ("int", "Int"):
                self.int_locals.add(p.name)
        args = ", ".join(f"BooleValue {self.c_ident(p.name)}" for p in node.params) or "void"
        self.emit(f"static BooleValue {self.c_ident(node.name)}({args}) {{")
        self.indent += 1
        self.body_start = len(self.lines)
        # unbox int params
        for p in node.params:
            if p.name in self.int_locals:
                self.emit(f"int64_t {self.c_ident(p.name)}_i = bv_as_int({self.c_ident(p.name)});")
        for stmt in node.body:
            self.gen_stmt(stmt)
        self.emit("return bv_none();")
        self._flush_decls()
        self.indent -= 1
        self.emit("}")
        text = "\n".join(self.lines)
        (
            self.lines,
            self.indent,
            self.locals,
            self.boxed_locals,
            self.int_locals,
            self.decls,
            self.body_start,
        ) = saved
        return text

    def ensure_val(self, name: str):
        if name in self.fn_names:
            return
        if name not in self.boxed_locals:
            self.decls.append(f"BooleValue {self.c_ident(name)} = bv_none();")
            self.boxed_locals.add(name)
        self.locals.add(name)

    def ensure_int(self, name: str):
        if name not in self.int_locals:
            self.decls.append(f"int64_t {self.c_ident(name)}_i = 0;")
            self.int_locals.add(name)
        self.locals.add(name)

    def demote_int(self, name: str):
        """Move an int local into a boxed BooleValue before a non-int write/read mix."""
        if name not in self.int_locals:
            return
        self.ensure_val(name)
        self.emit(f"bv_release({self.c_ident(name)});")
        self.emit(f"{self.c_ident(name)} = bv_int({self.c_ident(name)}_i);")
        self.int_locals.discard(name)

    def _assigned_in(self, stmts, names: set[str]):
        for stmt in stmts:
            if isinstance(stmt, (A.Assign, A.AnnAssign, A.AugAssign)) and isinstance(
                stmt.target, A.Name
            ):
                if stmt.target.id in self.int_locals:
                    # Non-int RHS (under current int_locals) forces a demotion.
                    if isinstance(stmt, A.AugAssign):
                        if not self.is_int_expr(stmt.value):
                            names.add(stmt.target.id)
                    elif stmt.value is not None and not self.is_int_expr(stmt.value):
                        names.add(stmt.target.id)
            if isinstance(stmt, A.IfStmt):
                self._assigned_in(stmt.body, names)
                for _c, body in stmt.elifs:
                    self._assigned_in(body, names)
                if stmt.else_body:
                    self._assigned_in(stmt.else_body, names)
            elif isinstance(stmt, (A.WhileStmt, A.ForStmt)):
                self._assigned_in(stmt.body, names)

    def demote_before_loop(self, body):
        """Demote int locals once before a loop so the body does not reset from _i each pass."""
        names: set[str] = set()
        self._assigned_in(body, names)
        for name in sorted(names):
            self.demote_int(name)

    def is_int_expr(self, node) -> bool:
        if isinstance(node, A.Literal) and isinstance(node.value, int) and not isinstance(node.value, bool):
            return True
        if isinstance(node, A.Name) and node.id in self.int_locals:
            return True
        if isinstance(node, A.Unary) and node.op in ("+", "-") and self.is_int_expr(node.operand):
            return True
        if isinstance(node, A.Binary) and node.op in ("+", "-", "*", "//", "%") and self.is_int_expr(
            node.left
        ) and self.is_int_expr(node.right):
            return True
        if isinstance(node, A.Call) and isinstance(node.func, A.Name):
            if node.func.id == "int" and len(node.args) == 1:
                return True
            if node.func.id in self.fn_names:
                # unknown; treat as boxed
                return False
        return False

    def gen_int(self, node) -> str:
        """Emit int64 expression; returns a C expression string (may use temps)."""
        if isinstance(node, A.Literal) and isinstance(node.value, int) and not isinstance(node.value, bool):
            return f"{node.value}LL"
        if isinstance(node, A.Name) and node.id in self.int_locals:
            return f"{self.c_ident(node.id)}_i"
        if isinstance(node, A.Unary):
            a = self.gen_int(node.operand)
            if node.op == "-":
                return f"(-({a}))"
            return f"(+({a}))"
        if isinstance(node, A.Binary):
            a = self.gen_int(node.left)
            b = self.gen_int(node.right)
            op = {"+": "+", "-": "-", "*": "*", "//": "/", "%": "%"}[node.op]
            t = self.fresh("i")
            self.emit(f"int64_t {t} = ({a}) {op} ({b});")
            return t
        if isinstance(node, A.Call) and isinstance(node.func, A.Name) and node.func.id == "int":
            v = self.gen_expr(node.args[0])
            boxed = self.fresh("iv")
            t = self.fresh("i")
            self.emit(f"BooleValue {boxed} = bv_call_int({v});")
            self.emit(f"bv_release({v});")
            self.emit(f"int64_t {t} = bv_as_int({boxed});")
            return t
        # fallback: box path then unbox
        v = self.gen_expr(node)
        t = self.fresh("i")
        self.emit(f"int64_t {t} = bv_as_int({v});")
        self.emit(f"bv_release({v});")
        return t

    def box_int(self, c_expr: str) -> str:
        t = self.fresh("box")
        self.emit(f"BooleValue {t} = bv_int({c_expr});")
        return t

    def gen_stmt(self, node):
        if isinstance(node, A.Assign):
            if isinstance(node.target, A.Name) and self.is_int_expr(node.value):
                self.ensure_int(node.target.id)
                rhs = self.gen_int(node.value)
                self.emit(f"{self.c_ident(node.target.id)}_i = {rhs};")
                return
            # Demote before RHS so loop bodies don't keep reading a stale _i.
            if isinstance(node.target, A.Name) and node.target.id in self.int_locals:
                self.demote_int(node.target.id)
            val = self.gen_expr(node.value)
            if isinstance(node.target, A.Name):
                self.ensure_val(node.target.id)
                self.emit(f"bv_release({self.c_ident(node.target.id)});")
                self.emit(f"{self.c_ident(node.target.id)} = {val};")
                return
            if isinstance(node.target, A.Index):
                obj = self.gen_expr(node.target.value)
                idx = self.gen_expr(node.target.index)
                self.emit(f"bv_index_set({obj}, {idx}, {val});")
                self.emit(f"bv_release({obj});")
                self.emit(f"bv_release({idx});")
                return
            if isinstance(node.target, A.Attribute):
                obj = self.gen_expr(node.target.value)
                self.emit(f'bv_setattr({obj}, "{node.target.attr}", {val});')
                self.emit(f"bv_release({obj});")
                return
            self.unsupported(node, "unsupported assignment target")
        if isinstance(node, A.AnnAssign):
            if node.value is None:
                if isinstance(node.target, A.Name):
                    if isinstance(node.typ, A.NamedType) and node.typ.name in ("int", "Int"):
                        self.ensure_int(node.target.id)
                    else:
                        self.ensure_val(node.target.id)
                return
            want_int = isinstance(node.target, A.Name) and (
                self.is_int_expr(node.value)
                or (isinstance(node.typ, A.NamedType) and node.typ.name in ("int", "Int"))
            )
            if want_int and self.is_int_expr(node.value):
                self.ensure_int(node.target.id)
                rhs = self.gen_int(node.value)
                self.emit(f"{self.c_ident(node.target.id)}_i = {rhs};")
                return
            if isinstance(node.target, A.Name) and node.target.id in self.int_locals:
                self.demote_int(node.target.id)
            val = self.gen_expr(node.value)
            if isinstance(node.target, A.Name):
                self.ensure_val(node.target.id)
                self.emit(f"bv_release({self.c_ident(node.target.id)});")
                self.emit(f"{self.c_ident(node.target.id)} = {val};")
                return
            self.unsupported(node, "unsupported annotated assign")
        if isinstance(node, A.AugAssign):
            if isinstance(node.target, A.Name) and node.target.id in self.int_locals and self.is_int_expr(
                node.value
            ):
                rhs = self.gen_int(node.value)
                op = {"+": "+", "-": "-", "*": "*", "/": "/", "//": "/", "%": "%", "**": None}[node.op]
                if op is None:
                    self.unsupported(node, "int **= use boxed path")
                self.emit(f"{self.c_ident(node.target.id)}_i {op}= {rhs};")
                return
            ops = {
                "+": "bv_add",
                "-": "bv_sub",
                "*": "bv_mul",
                "/": "bv_div",
                "//": "bv_floordiv",
                "%": "bv_mod",
                "**": "bv_pow",
            }
            if isinstance(node.target, A.Attribute):
                obj = self.gen_expr(node.target.value)
                cur = self.fresh("ag")
                self.emit(f'BooleValue {cur} = bv_getattr({obj}, "{node.target.attr}");')
                right = self.gen_expr(node.value)
                tmp = self.fresh("aug")
                self.emit(f"BooleValue {tmp} = {ops[node.op]}({cur}, {right});")
                self.emit(f"bv_release({cur});")
                self.emit(f"bv_release({right});")
                self.emit(f'bv_setattr({obj}, "{node.target.attr}", {tmp});')
                self.emit(f"bv_release({obj});")
                return
            if not isinstance(node.target, A.Name):
                self.unsupported(node, "augassign only on names or attributes")
            if node.target.id in self.int_locals:
                self.demote_int(node.target.id)
            self.ensure_val(node.target.id)
            right = self.gen_expr(node.value)
            left = self.c_ident(node.target.id)
            tmp = self.fresh("aug")
            self.emit(f"BooleValue {tmp} = {ops[node.op]}({left}, {right});")
            self.emit(f"bv_release({right});")
            self.emit(f"bv_release({left});")
            self.emit(f"{left} = {tmp};")
            return
        if isinstance(node, A.ExprStmt):
            v = self.gen_expr(node.expr)
            self.emit(f"bv_release({v});")
            return
        if isinstance(node, A.ReturnStmt):
            if node.value is None:
                self.emit("return bv_none();")
            elif self.is_int_expr(node.value):
                self.emit(f"return bv_int({self.gen_int(node.value)});")
            else:
                self.emit(f"return {self.gen_expr(node.value)};")
            return
        if isinstance(node, A.IfStmt):
            done = self.fresh("done")
            self.emit(f"int {done} = 0;")
            branches = [(node.cond, node.body)] + list(node.elifs)
            for cond_node, body in branches:
                self.emit(f"if (!{done}) {{")
                self.indent += 1
                if self._is_simple_int_cmp(cond_node):
                    flag = self._emit_int_cmp(cond_node)
                else:
                    cond = self.gen_expr(cond_node)
                    flag = self.fresh("iff")
                    self.emit(f"int {flag} = bv_truthy({cond});")
                    self.emit(f"bv_release({cond});")
                self.emit(f"if ({flag}) {{")
                self.indent += 1
                self.emit(f"{done} = 1;")
                for s in body:
                    self.gen_stmt(s)
                self.indent -= 1
                self.emit("}")
                self.indent -= 1
                self.emit("}")
            if node.else_body is not None:
                self.emit(f"if (!{done}) {{")
                self.indent += 1
                for s in node.else_body:
                    self.gen_stmt(s)
                self.indent -= 1
                self.emit("}")
            return
        if isinstance(node, A.WhileStmt):
            self.demote_before_loop(node.body)
            self.emit("while (1) {")
            self.indent += 1
            if self._is_simple_int_cmp(node.cond):
                flag = self._emit_int_cmp(node.cond)
            else:
                cond = self.gen_expr(node.cond)
                flag = self.fresh("wf")
                self.emit(f"int {flag} = bv_truthy({cond});")
                self.emit(f"bv_release({cond});")
            self.emit(f"if (!{flag}) break;")
            for s in node.body:
                self.gen_stmt(s)
            self.indent -= 1
            self.emit("}")
            return
        if isinstance(node, A.ForStmt):
            # for x in range(...): → C for
            if (
                isinstance(node.iterable, A.Call)
                and isinstance(node.iterable.func, A.Name)
                and node.iterable.func.id == "range"
            ):
                args = node.iterable.args
                self.ensure_int(node.name)
                # Body may still mix boxed values into other ints — demote those first.
                self.demote_before_loop(node.body)
                if len(args) == 1:
                    stop = self.gen_int(args[0])
                    self.emit(f"for ({self.c_ident(node.name)}_i = 0; {self.c_ident(node.name)}_i < ({stop}); {self.c_ident(node.name)}_i++) {{")
                elif len(args) == 2:
                    start = self.gen_int(args[0])
                    stop = self.gen_int(args[1])
                    self.emit(
                        f"for ({self.c_ident(node.name)}_i = ({start}); {self.c_ident(node.name)}_i < ({stop}); {self.c_ident(node.name)}_i++) {{"
                    )
                elif len(args) == 3:
                    start = self.gen_int(args[0])
                    stop = self.gen_int(args[1])
                    step = self.gen_int(args[2])
                    self.emit(
                        f"for ({self.c_ident(node.name)}_i = ({start}); ({step}) > 0 ? {self.c_ident(node.name)}_i < ({stop}) : {self.c_ident(node.name)}_i > ({stop}); {self.c_ident(node.name)}_i += ({step})) {{"
                    )
                else:
                    self.unsupported(node, "bad range")
                self.indent += 1
                for s in node.body:
                    self.gen_stmt(s)
                self.indent -= 1
                self.emit("}")
                return
            # List/other iterators: loop var is boxed; demote ints the body will mix.
            self.demote_before_loop(node.body)
            it = self.gen_expr(node.iterable)
            idx = self.fresh("i")
            seq = self.fresh("seq")
            nlen = self.fresh("n")
            self.emit(f"BooleValue {seq} = {it};")
            self.ensure_val(node.name)
            self.int_locals.discard(node.name)
            self.emit(f"int64_t {nlen} = bv_as_int(bv_call_len({seq}));")
            self.emit(f"for (int64_t {idx} = 0; {idx} < {nlen}; {idx}++) {{")
            self.indent += 1
            get = self.fresh("it")
            self.emit(f"BooleValue {get} = bv_list_get({seq}, bv_int({idx}));")
            self.emit(f"bv_release({self.c_ident(node.name)});")
            self.emit(f"{self.c_ident(node.name)} = {get};")
            for s in node.body:
                self.gen_stmt(s)
            self.indent -= 1
            self.emit("}")
            self.emit(f"bv_release({seq});")
            return
        if isinstance(node, A.PassStmt):
            self.emit("/* pass */")
            return
        if isinstance(node, A.AssertStmt):
            if self._is_simple_int_cmp(node.cond):
                flag = self._emit_int_cmp(node.cond)
                self.emit(f"if (!{flag}) bv_die(\"assertion failed\");")
            else:
                cond = self.gen_expr(node.cond)
                self.emit(f"if (!bv_truthy({cond})) bv_die(\"assertion failed\");")
                self.emit(f"bv_release({cond});")
            return
        if isinstance(node, A.BreakStmt):
            self.emit("break;")
            return
        if isinstance(node, A.ContinueStmt):
            self.emit("continue;")
            return
        if isinstance(node, A.RaiseStmt):
            if node.message is None:
                self.emit(f'bv_raise("{node.exc}", "");')
            else:
                msg = self.gen_expr(node.message)
                self.emit(f'bv_raise("{node.exc}", bv_as_cstr(bv_call_str({msg})));')
                self.emit(f"bv_release({msg});")
            return
        if isinstance(node, A.TryStmt):
            self.gen_try(node)
            return
        if isinstance(node, (A.FuncDef, A.ClassDef, A.ImportStmt)):
            return
        self.unsupported(node, f"unsupported statement {type(node).__name__}")

    def gen_try(self, node: A.TryStmt):
        frame = self.fresh("ef")
        self.emit(f"BooleExcFrame *{frame} = bv_exc_push();")
        self.emit(f"if (setjmp({frame}->buf) == 0) {{")
        self.indent += 1
        for s in node.body:
            self.gen_stmt(s)
        self.emit("bv_exc_pop();")
        self.indent -= 1
        self.emit("} else {")
        self.indent += 1
        if not node.handlers:
            self.emit("bv_exc_pop();")
            self.emit("bv_exc_reraise();")
        else:
            first = True
            for exc_name, as_name, body in node.handlers:
                catch = exc_name or "Exception"
                cond = f'bv_exc_match("{catch}")'
                keyword = "if" if first else "else if"
                first = False
                self.emit(f"{keyword} ({cond}) {{")
                self.indent += 1
                if as_name:
                    self.ensure_val(as_name)
                    self.emit(
                        f"bv_release({self.c_ident(as_name)}); "
                        f'{self.c_ident(as_name)} = bv_str(bv_exc_msg());'
                    )
                self.emit("bv_exc_clear();")
                self.emit("bv_exc_pop();")
                for s in body:
                    self.gen_stmt(s)
                self.indent -= 1
                self.emit("}")
            self.emit("else {")
            self.indent += 1
            self.emit("bv_exc_pop();")
            self.emit("bv_exc_reraise();")
            self.indent -= 1
            self.emit("}")
        self.indent -= 1
        self.emit("}")
        if node.final:
            for s in node.final:
                self.gen_stmt(s)

    def _is_simple_int_cmp(self, node) -> bool:
        return (
            isinstance(node, A.Compare)
            and len(node.ops) == 1
            and node.ops[0] in ("<", "<=", ">", ">=", "==", "!=")
            and self.is_int_expr(node.left)
            and self.is_int_expr(node.comparators[0])
        )

    def _emit_int_cmp(self, node: A.Compare) -> str:
        a = self.gen_int(node.left)
        b = self.gen_int(node.comparators[0])
        op = {"<": "<", "<=": "<=", ">": ">", ">=": ">=", "==": "==", "!=": "!="}[node.ops[0]]
        flag = self.fresh("cmp")
        self.emit(f"int {flag} = ({a}) {op} ({b});")
        return flag

    def gen_expr(self, node) -> str:
        if self.is_int_expr(node) and not isinstance(node, A.Name):
            # Keep names as retainable values when used as expr in boxed context;
            # for pure int trees, box at the end.
            return self.box_int(self.gen_int(node))
        if isinstance(node, A.Literal):
            t = self.fresh()
            v = node.value
            if v is None:
                self.emit(f"BooleValue {t} = bv_none();")
            elif isinstance(v, bool):
                self.emit(f"BooleValue {t} = bv_bool({1 if v else 0});")
            elif isinstance(v, int):
                self.emit(f"BooleValue {t} = bv_int({v}LL);")
            elif isinstance(v, float):
                self.emit(f"BooleValue {t} = bv_float({v!r});")
            elif isinstance(v, str):
                esc = v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
                self.emit(f'BooleValue {t} = bv_str("{esc}");')
            else:
                self.unsupported(node, "unsupported literal")
            return t
        if isinstance(node, A.Name):
            if node.id in ("True", "False", "None"):
                t = self.fresh()
                mapping = {"True": "bv_bool(1)", "False": "bv_bool(0)", "None": "bv_none()"}
                self.emit(f"BooleValue {t} = {mapping[node.id]};")
                return t
            if node.id in self.fn_names:
                self.unsupported(node, "first-class functions: use interpreter")
            if node.id in self.int_locals:
                return self.box_int(f"{self.c_ident(node.id)}_i")
            self.ensure_val(node.id)
            t = self.fresh()
            self.emit(f"BooleValue {t} = bv_retain({self.c_ident(node.id)});")
            return t
        if isinstance(node, A.ListLit):
            t = self.fresh("lst")
            self.emit(f"BooleValue {t} = bv_list();")
            for e in node.elts:
                ev = self.gen_expr(e)
                self.emit(f"bv_list_push({t}, {ev});")
            return t
        if isinstance(node, A.DictLit):
            t = self.fresh("d")
            self.emit(f"BooleValue {t} = bv_dict();")
            for k, v in zip(node.keys, node.values):
                kk = self.gen_expr(k)
                vv = self.gen_expr(v)
                self.emit(f"bv_dict_set({t}, {kk}, {vv});")
            return t
        if isinstance(node, A.FString):
            t = self.fresh("fs")
            self.emit(f'BooleValue {t} = bv_str("");')
            for part in node.parts:
                if part[0] == "text":
                    esc = part[1].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
                    piece = self.fresh("fp")
                    self.emit(f'BooleValue {piece} = bv_str("{esc}");')
                else:
                    ev = self.gen_expr(part[1])
                    piece = self.fresh("fstr")
                    self.emit(f"BooleValue {piece} = bv_call_str({ev});")
                    self.emit(f"bv_release({ev});")
                joined = self.fresh("fj")
                self.emit(f"BooleValue {joined} = bv_add({t}, {piece});")
                self.emit(f"bv_release({t});")
                self.emit(f"bv_release({piece});")
                t = joined
            return t
        if isinstance(node, A.Unary):
            if node.op == "not":
                if self._is_simple_int_cmp(node.operand):
                    flag = self._emit_int_cmp(node.operand)
                    t = self.fresh()
                    self.emit(f"BooleValue {t} = bv_bool(!{flag});")
                    return t
                a = self.gen_expr(node.operand)
                t = self.fresh()
                self.emit(f"BooleValue {t} = bv_bool(!bv_truthy({a}));")
                self.emit(f"bv_release({a});")
                return t
            if self.is_int_expr(node):
                return self.box_int(self.gen_int(node))
            a = self.gen_expr(node.operand)
            t = self.fresh()
            if node.op == "-":
                self.emit(f"BooleValue {t} = bv_neg({a});")
            else:
                self.emit(f"BooleValue {t} = {a};")
            if node.op == "-":
                self.emit(f"bv_release({a});")
            return t
        if isinstance(node, A.Binary):
            if self.is_int_expr(node):
                return self.box_int(self.gen_int(node))
            a = self.gen_expr(node.left)
            b = self.gen_expr(node.right)
            t = self.fresh()
            ops = {
                "+": "bv_add",
                "-": "bv_sub",
                "*": "bv_mul",
                "/": "bv_div",
                "//": "bv_floordiv",
                "%": "bv_mod",
                "**": "bv_pow",
            }
            self.emit(f"BooleValue {t} = {ops[node.op]}({a}, {b});")
            self.emit(f"bv_release({a});")
            self.emit(f"bv_release({b});")
            return t
        if isinstance(node, A.BoolOp):
            t = self.fresh("b")
            a = self.gen_expr(node.left)
            if node.op == "and":
                self.emit(f"BooleValue {t};")
                self.emit(f"if (!bv_truthy({a})) {{ {t} = {a}; }}")
                self.emit("else {")
                self.indent += 1
                self.emit(f"bv_release({a});")
                b = self.gen_expr(node.right)
                self.emit(f"{t} = {b};")
                self.indent -= 1
                self.emit("}")
            else:
                self.emit(f"BooleValue {t};")
                self.emit(f"if (bv_truthy({a})) {{ {t} = {a}; }}")
                self.emit("else {")
                self.indent += 1
                self.emit(f"bv_release({a});")
                b = self.gen_expr(node.right)
                self.emit(f"{t} = {b};")
                self.indent -= 1
                self.emit("}")
            return t
        if isinstance(node, A.Compare):
            if self._is_simple_int_cmp(node):
                flag = self._emit_int_cmp(node)
                t = self.fresh("cmp")
                self.emit(f"BooleValue {t} = bv_bool({flag});")
                return t
            left = self.gen_expr(node.left)
            t = self.fresh("cmp")
            cur = self.fresh("cur")
            self.emit(f"BooleValue {t} = bv_bool(1);")
            self.emit(f"BooleValue {cur} = {left};")
            for op, comp in zip(node.ops, node.comparators):
                right = self.gen_expr(comp)
                ok = self.fresh("ok")
                if op == "==":
                    self.emit(f"int {ok} = bv_eq({cur}, {right});")
                elif op == "!=":
                    self.emit(f"int {ok} = !bv_eq({cur}, {right});")
                elif op == "<":
                    self.emit(f"int {ok} = bv_lt({cur}, {right});")
                elif op == "<=":
                    self.emit(f"int {ok} = bv_le({cur}, {right});")
                elif op == ">":
                    self.emit(f"int {ok} = bv_gt({cur}, {right});")
                elif op == ">=":
                    self.emit(f"int {ok} = bv_ge({cur}, {right});")
                else:
                    self.unsupported(node, f"compare {op}")
                self.emit(f"if (!{ok}) {{")
                self.indent += 1
                self.emit(f"bv_release({t}); {t} = bv_bool(0);")
                self.emit(f"bv_release({cur}); bv_release({right}); {cur} = bv_none();")
                self.indent -= 1
                self.emit("} else {")
                self.indent += 1
                self.emit(f"bv_release({cur}); {cur} = {right};")
                self.indent -= 1
                self.emit("}")
            self.emit(f"bv_release({cur});")
            return t
        if isinstance(node, A.Ternary):
            t = self.fresh("ter")
            c = self.gen_expr(node.cond)
            self.emit(f"BooleValue {t};")
            self.emit(f"if (bv_truthy({c})) {{")
            self.indent += 1
            self.emit(f"bv_release({c});")
            a = self.gen_expr(node.body)
            self.emit(f"{t} = {a};")
            self.indent -= 1
            self.emit("} else {")
            self.indent += 1
            self.emit(f"bv_release({c});")
            b = self.gen_expr(node.orelse)
            self.emit(f"{t} = {b};")
            self.indent -= 1
            self.emit("}")
            return t
        if isinstance(node, A.Call):
            return self.gen_call(node)
        if isinstance(node, A.Index):
            obj = self.gen_expr(node.value)
            idx = self.gen_expr(node.index)
            t = self.fresh("ix")
            self.emit(f"BooleValue {t} = bv_index_get({obj}, {idx});")
            self.emit(f"bv_release({obj});")
            self.emit(f"bv_release({idx});")
            return t
        if isinstance(node, A.Slice):
            obj = self.gen_expr(node.value)
            s = self.gen_expr(node.start) if node.start else None
            e = self.gen_expr(node.stop) if node.stop else None
            if s is None:
                s = self.fresh("st")
                self.emit(f"BooleValue {s} = bv_none();")
            if e is None:
                e = self.fresh("sp")
                self.emit(f"BooleValue {e} = bv_none();")
            t = self.fresh("sl")
            self.emit(f"BooleValue {t} = bv_slice({obj}, {s}, {e});")
            self.emit(f"bv_release({obj}); bv_release({s}); bv_release({e});")
            return t
        if isinstance(node, A.Attribute):
            obj = self.gen_expr(node.value)
            t = self.fresh("at")
            self.emit(f'BooleValue {t} = bv_getattr({obj}, "{node.attr}");')
            self.emit(f"bv_release({obj});")
            return t
        self.unsupported(node, f"unsupported expr {type(node).__name__}")
        return "bv_none()"

    def gen_call(self, node: A.Call) -> str:
        if node.keywords:
            self.unsupported(node, "keyword args: use interpreter")
        t = self.fresh("call")

        # obj.method(args) or module.fn(args)
        if isinstance(node.func, A.Attribute):
            obj = self.gen_expr(node.func.value)
            args = [self.gen_expr(a) for a in node.args]
            n = len(args)
            self.emit(f"BooleValue {t};")
            if n == 0:
                self.emit(f"if ({obj}.tag == BV_INSTANCE) {{")
                self.indent += 1
                self.emit(
                    f'{t} = bv_call_method({obj}, "{node.func.attr}", 0, NULL);'
                )
                self.indent -= 1
                self.emit("} else {")
                self.indent += 1
                fn = self.fresh("fn")
                self.emit(f'BooleValue {fn} = bv_getattr({obj}, "{node.func.attr}");')
                self.emit(f"{t} = bv_call_value({fn}, 0, NULL);")
                self.emit(f"bv_release({fn});")
                self.indent -= 1
                self.emit("}")
            else:
                arr = self.fresh("args")
                self.emit(f"BooleValue {arr}[{n}];")
                for i, a in enumerate(args):
                    self.emit(f"{arr}[{i}] = {a};")
                self.emit(f"if ({obj}.tag == BV_INSTANCE) {{")
                self.indent += 1
                self.emit(
                    f'{t} = bv_call_method({obj}, "{node.func.attr}", {n}, {arr});'
                )
                self.indent -= 1
                self.emit("} else {")
                self.indent += 1
                fn = self.fresh("fn")
                self.emit(f'BooleValue {fn} = bv_getattr({obj}, "{node.func.attr}");')
                self.emit(f"{t} = bv_call_value({fn}, {n}, {arr});")
                self.emit(f"bv_release({fn});")
                self.indent -= 1
                self.emit("}")
                for a in args:
                    self.emit(f"bv_release({a});")
            self.emit(f"bv_release({obj});")
            return t

        if not isinstance(node.func, A.Name):
            # generic callable value
            callee = self.gen_expr(node.func)
            args = [self.gen_expr(a) for a in node.args]
            n = len(args)
            if n == 0:
                self.emit(f"BooleValue {t} = bv_call_value({callee}, 0, NULL);")
            else:
                arr = self.fresh("args")
                self.emit(f"BooleValue {arr}[{n}];")
                for i, a in enumerate(args):
                    self.emit(f"{arr}[{i}] = {a};")
                self.emit(f"BooleValue {t} = bv_call_value({callee}, {n}, {arr});")
                for a in args:
                    self.emit(f"bv_release({a});")
            self.emit(f"bv_release({callee});")
            return t

        name = node.func.id
        args = [self.gen_expr(a) for a in node.args]

        def release_args():
            for a in args:
                self.emit(f"bv_release({a});")

        # Class constructor
        if name in self.class_names:
            n = len(args)
            if n == 0:
                self.emit(
                    f"BooleValue {t} = bv_call_value({self.c_ident(name)}, 0, NULL);"
                )
            else:
                arr = self.fresh("args")
                self.emit(f"BooleValue {arr}[{n}];")
                for i, a in enumerate(args):
                    self.emit(f"{arr}[{i}] = {a};")
                self.emit(
                    f"BooleValue {t} = bv_call_value({self.c_ident(name)}, {n}, {arr});"
                )
                release_args()
            return t

        if name == "print":
            if not args:
                self.emit(f"BooleValue {t} = bv_call_print(0, NULL);")
            else:
                arr = self.fresh("args")
                self.emit(f"BooleValue {arr}[{len(args)}];")
                for i, a in enumerate(args):
                    self.emit(f"{arr}[{i}] = {a};")
                self.emit(f"BooleValue {t} = bv_call_print({len(args)}, {arr});")
                for i in range(len(args)):
                    self.emit(f"bv_release({arr}[{i}]);")
            return t
        builtins = {
            "len": ("bv_call_len", 1),
            "str": ("bv_call_str", 1),
            "int": ("bv_call_int", 1),
            "float": ("bv_call_float", 1),
            "bool": ("bv_call_bool", 1),
            "sorted": ("bv_call_sorted", 1),
            "sum": ("bv_call_sum", 1),
            "abs": ("bv_call_abs", 1),
            "type": ("bv_call_type", 1),
        }
        if name in builtins and len(args) == builtins[name][1]:
            self.emit(f"BooleValue {t} = {builtins[name][0]}({args[0]});")
            self.emit(f"bv_release({args[0]});")
            return t
        if name in ("range", "max", "min"):
            fn = {"range": "bv_call_range", "max": "bv_call_max", "min": "bv_call_min"}[name]
            arr = self.fresh("args")
            self.emit(f"BooleValue {arr}[{max(len(args), 1)}];")
            for i, a in enumerate(args):
                self.emit(f"{arr}[{i}] = {a};")
            self.emit(f"BooleValue {t} = {fn}({len(args)}, {arr});")
            release_args()
            return t
        if name in self.fn_names:
            call_args = ", ".join(args) if args else ""
            self.emit(f"BooleValue {t} = {self.c_ident(name)}({call_args});")
            release_args()
            return t
        self.unsupported(node, f"unsupported call {name}")
        return "bv_none()"


def generate_c(program: A.Program, path: str = "<stdin>") -> str:
    return CGen(path).generate(program)
